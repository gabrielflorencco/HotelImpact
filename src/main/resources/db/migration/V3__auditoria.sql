-- V3 — Auditoria de operações de negócio: registro histórico imutável de
-- quem executou cada transição crítica (check-in/out, pagamentos, reservas,
-- limpezas e manutenções). Nenhum dado sensível — apenas usuário,
-- operação, entidade afetada e data.

CREATE TABLE public.registro_auditoria (
    id bigint NOT NULL,
    operacao character varying(30) NOT NULL,
    usuario character varying(60) NOT NULL,
    entidade_tipo character varying(30) NOT NULL,
    entidade_id bigint NOT NULL,
    data_hora timestamp(6) without time zone NOT NULL,
    detalhe character varying(300),
    CONSTRAINT registro_auditoria_pkey PRIMARY KEY (id),
    CONSTRAINT registro_auditoria_operacao_check CHECK (((operacao)::text = ANY ((ARRAY['RESERVA_CRIADA'::character varying, 'RESERVA_EDITADA'::character varying, 'RESERVA_CANCELADA'::character varying, 'RESERVA_NO_SHOW'::character varying, 'CHECK_IN'::character varying, 'CHECK_OUT'::character varying, 'CONSUMO_LANCADO'::character varying, 'CONSUMO_CANCELADO'::character varying, 'PAGAMENTO_REGISTRADO'::character varying, 'PAGAMENTO_ESTORNADO'::character varying, 'LIMPEZA_INICIADA'::character varying, 'LIMPEZA_CONCLUIDA'::character varying, 'MANUTENCAO_ABERTA'::character varying, 'MANUTENCAO_INICIADA'::character varying, 'MANUTENCAO_CONCLUIDA'::character varying, 'MANUTENCAO_CANCELADA'::character varying])::text[])))
);

CREATE INDEX idx_auditoria_data ON public.registro_auditoria USING btree (data_hora);
CREATE INDEX idx_auditoria_entidade ON public.registro_auditoria USING btree (entidade_tipo, entidade_id);

ALTER TABLE public.registro_auditoria ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.registro_auditoria_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
